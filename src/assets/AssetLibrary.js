import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { DRACOLoader } from 'three/addons/loaders/DRACOLoader.js';
import { KTX2Loader } from 'three/addons/loaders/KTX2Loader.js';
import { MeshoptDecoder } from 'three/addons/libs/meshopt_decoder.module.js';
import { SRGBColorSpace, TextureLoader, EquirectangularReflectionMapping } from 'three';
import { HDRLoader } from 'three/addons/loaders/HDRLoader.js';
import { MANIFEST, TEXTURES } from './manifest.js';

const BASE = import.meta.env.BASE_URL || '/';

/**
 * AssetLibrary — loads whatever BlendKit assets exist, reports the rest as
 * procedural. It never fetches a file that isn't listed in
 * /assets/asset-index.json (generated by scripts/build-asset-index.mjs), so an
 * empty asset folder produces zero 404s.
 */
export class AssetLibrary {
  constructor(renderer) {
    this.renderer = renderer;
    this.index = new Set();
    this.gltfs = new Map();
    this.textures = new Map();
    this.audioFiles = new Set();
    this.report = { loaded: [], procedural: [], failed: [] };

    const draco = new DRACOLoader().setDecoderPath(`${BASE}decoders/draco/`);
    const ktx2 = new KTX2Loader().setTranscoderPath(`${BASE}decoders/basis/`).detectSupport(renderer);
    this.gltfLoader = new GLTFLoader().setDRACOLoader(draco).setKTX2Loader(ktx2).setMeshoptDecoder(MeshoptDecoder);
    this.textureLoader = new TextureLoader();
  }

  async init() {
    try {
      const res = await fetch(`${BASE}assets/asset-index.json`, { cache: 'no-store' });
      if (res.ok) {
        const data = await res.json();
        for (const f of data.files || []) this.index.add(f);
      }
    } catch {
      // No index → everything is procedural. That is a supported state.
    }
    for (const f of this.index) if (f.startsWith('audio/')) this.audioFiles.add(f);
  }

  has(path) {
    return this.index.has(path);
  }

  /** Load every manifest GLB that exists. `onProgress(fraction, label)`. */
  async loadModels(onProgress) {
    const ids = Object.keys(MANIFEST);
    let done = 0;
    await Promise.all(
      ids.map(async (id) => {
        const entry = MANIFEST[id];
        if (!this.has(entry.file)) {
          this.report.procedural.push(id);
        } else {
          try {
            const gltf = await this.gltfLoader.loadAsync(`${BASE}assets/${entry.file}`);
            this._validate(id, entry, gltf);
            this.gltfs.set(id, gltf);
            this.report.loaded.push(id);
          } catch (err) {
            console.warn(`[assets] ${entry.file} failed to load — using procedural fallback`, err);
            this.report.failed.push(id);
          }
        }
        done++;
        if (onProgress) onProgress(done / ids.length, id);
      })
    );
    for (const [id, path] of Object.entries(TEXTURES)) {
      if (!this.has(path)) continue;
      try {
        let tex;
        if (path.endsWith('.hdr')) {
          tex = await new HDRLoader().loadAsync(`${BASE}assets/${path}`);
          tex.mapping = EquirectangularReflectionMapping;
        } else {
          tex = await this.textureLoader.loadAsync(`${BASE}assets/${path}`);
          tex.colorSpace = SRGBColorSpace;
          tex.anisotropy = 8;
        }
        this.textures.set(id, tex);
      } catch (err) {
        console.warn(`[assets] texture ${path} failed`, err);
      }
    }
    if (this.report.loaded.length) console.info('[assets] BlendKit assets in use:', this.report.loaded.join(', '));
  }

  /** Returns the loaded glTF (scene, animations, …) or null → caller builds procedural. */
  gltf(id) {
    return this.gltfs.get(id) || null;
  }

  texture(id) {
    return this.textures.get(id) || null;
  }

  /** Audio cue file, if one was dropped in /public/assets/audio (mp3, ogg, wav, m4a). */
  audioUrl(cue) {
    for (const ext of ['ogg', 'mp3', 'm4a', 'wav']) {
      const p = `audio/${cue}.${ext}`;
      if (this.audioFiles.has(p)) return `${BASE}assets/${p}`;
    }
    return null;
  }

  /** Warn (never throw) when a GLB is missing nodes the runtime relies on. */
  _validate(id, entry, gltf) {
    const names = new Set();
    gltf.scene.traverse((o) => names.add(o.name));
    const required = [...(entry.nodes || []), ...(entry.bones || [])];
    const missing = required.filter((n) => !names.has(n));
    if (missing.length) {
      console.warn(`[assets] ${entry.file}: missing node(s) ${missing.join(', ')} — related interactions fall back to defaults.`);
    }
    if (entry.clips && gltf.animations.length) {
      const clipNames = new Set(gltf.animations.map((a) => a.name));
      const missingClips = entry.clips.filter((c) => !clipNames.has(c));
      if (missingClips.length) console.warn(`[assets] ${entry.file}: missing clip(s) ${missingClips.join(', ')}`);
    }
  }
}
